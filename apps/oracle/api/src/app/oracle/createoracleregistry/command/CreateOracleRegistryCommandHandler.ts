import { Singleton, Handler, Validate, Inject, CommandHandler, Logger } from "@hashgraph/green-bonds-shared-core"
import { CreateOracleRegistryCommand } from "./CreateOracleRegistryCommand"
import type { OracleRegistryRepository } from "@domain/oracle/repositories/OracleRegistryRepository"
import { OracleRegistry } from "@domain/oracle/model/OracleRegistry"
import { Project } from "@domain/oracle/model/Project"
import { OracleRegistryFoundError } from "@domain/oracle/errors/OracleRegistryFoundError"

@Singleton()
@Handler(CreateOracleRegistryCommand)
export class CreateOracleRegistryCommandHandler implements CommandHandler<CreateOracleRegistryCommand, OracleRegistry> {
  private readonly logger = new Logger(CreateOracleRegistryCommandHandler.name)

  constructor(
    @Inject("OracleRegistryRepository")
    private readonly repository: OracleRegistryRepository,
  ) {}

  @Validate()
  async execute(command: CreateOracleRegistryCommand): Promise<OracleRegistry> {
    this.logger.log(
      `Creating oracle registry for bond ${command.bondContractId} with KPI contract ${command.kpiContractId}`,
    )

    // Check if KPI contract already has an oracle registry
    const existing = await this.repository.findByKpiContractId(command.kpiContractId)
    if (existing) {
      throw OracleRegistryFoundError.kpiContractIdError(command.kpiContractId)
    }

    // Create projects
    const projects = command.projects.map((p) => new Project(p.projectId, p.topicId))

    // Create registry (ID is generated by the domain model)
    const registry = OracleRegistry.create(
      command.bondContractId,
      command.kpiContractId,
      projects,
      command.schedulerStartDate,
      command.schedulerEndDate,
      command.frequencyMinutes,
    )

    // Save
    const saved = await this.repository.save(registry)

    this.logger.log(`Oracle registry created with ID: ${saved.id}`)

    return saved
  }
}
